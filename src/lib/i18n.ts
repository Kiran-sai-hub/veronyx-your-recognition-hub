const dictionaries: Record<string, Dictionary> = { en, hi, ta };

export const translatedLanguages = ["en", "hi", "ta"] as const;

export function translate(language: string, key: I18nKey, vars?: Record<string, string | number>) {
  const template = dictionaries[language]?.[key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function hasTranslation(language: string): boolean {
  return (translatedLanguages as readonly string[]).includes(language);
}

export function useT() {
  const language = useAppStore((s) => s.language);
  return (key: I18nKey, vars?: Record<string, string | number>) => translate(language, key, vars);
}
